"""Original 3x5 playfield title art for Fairly's Adventure."""
from pathlib import Path
FONT={
'A':['010','101','111','101','101'],'D':['110','101','101','101','110'],
'E':['11','10','11','10','11'],'F':['111','100','110','100','100'],
'I':['111','010','010','010','111'],'L':['100','100','100','100','111'],
'N':['1001','1101','1011','1001','1001'],'P':['110','101','110','100','100'],
'R':['110','101','110','101','101'],'S':['111','100','111','001','111'],
'T':['111','010','010','010','010'],'U':['101','101','101','101','111'],
'V':['101','101','101','101','010'],'Y':['101','101','010','010','010'],
"'":['010','010','000','000','000'],' ':['0']*5,
'O':['111','101','101','101','111']}
rows=[[0]*40 for _ in range(192)];colors=[0]*192
for y in range(8,184):
 if y<20 or y>=172:
  colors[y]=0x08 if y%6<4 else 0x04
  for x in range(40):rows[y][x]=int(y%6!=5 and (x+(5 if y//6%2 else 0))%10!=0)
 else:
  rows[y][0]=rows[y][39]=1;colors[y]=0x08
def text(word,top,height):
 starts=[];width=0
 for i,char in enumerate(word):
  starts.append(width);width+=len(FONT[char][0])
  if i<len(word)-1:width+=1
 left=(40-width)//2
 for line in range(5*height):
  y=top+line;rows[y]=[0]*40;colors[y]=0x1e
  for letter,char in enumerate(word):
   for dx,bit in enumerate(FONT[char][line//height]):rows[y][left+starts[letter]+dx]=int(bit)
text("FAIRLY'S",34,4);text('ADVENTURE',68,4)
text('PRESS FIRE',146,2);text('TO PLAY',160,2)
fields=[[] for _ in range(6)]
for row in rows:
 for half in range(2):
  bits=row[half*20:half*20+20]
  fields[half*3].append(sum(bits[i]<<(i+4) for i in range(4)))
  fields[half*3+1].append(sum(bits[i+4]<<(7-i) for i in range(8)))
  fields[half*3+2].append(sum(bits[i+12]<<i for i in range(8)))
def emit(name,values):
 return name+'\n'+''.join(' .byte '+','.join(f'${v:02X}' for v in values[i:i+16])+'\n' for i in range(0,len(values),16))
s='; Generated by make-title-art.py. 192 NTSC visible rows.\n'
for name,values in zip(('TitlePF0L','TitlePF1L','TitlePF2L','TitlePF0R','TitlePF1R','TitlePF2R'),fields):
 s+=' align 256\n'+emit(name,values)
s+=' align 256\n'+emit('TitleColors',colors)
for name,values in [('TitleHeroA',[0x10,0x3c,0x18,0x3b,0x39,0x7e,0x3c,0x66]),
                    ('TitleHeroB',[0x10,0x3c,0x18,0x3b,0x39,0x3e,0x7c,0x24]),
                    ('TitleHeroInk',[0x84,0x86,0x3e,0x3e,0x8a,0x88,0x86,0xf4]),
                    ('TitleSkeleton',[0x3c,0x5a,0x18,0x3c,0x5a,0x18,0x24,0x42])]:
 s+=emit(name,[v for v in values for _ in range(4)])
Path('title-art.inc').write_text(s)
print('Generated title, prompt, gray bricks, Fairly and skeleton')
